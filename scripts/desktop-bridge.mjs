// Writes Std.Desktop.Bridge from tools/pudu-js, or with --check fails when the
// committed module differs from what the sources would produce.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const target = new URL('packages/pudu/v0.1/lib/Std/Desktop/Bridge.pudu', root);

function literal(line) {
  return '"' + line.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\{/g, '\\{').replace(/\}/g, '\\}').replace(/\t/g, '\\t') + '"';
}

function table(name, text) {
  const lines = text.replace(/\n$/, '').split('\n').map((line) => `  ${literal(line)},`);
  return `const ${name}: Array[Str] = [\n${lines.join('\n')}\n]`;
}

const bridge = readFileSync(new URL('tools/pudu-js/bridge.js', root), 'utf8');
const declarations = readFileSync(new URL('tools/pudu-js/bridge.d.ts', root), 'utf8');

const module = `module Std.Desktop.Bridge

import Std.Json as Json

// Generated by scripts/desktop-bridge.mjs from tools/pudu-js; edit those sources.

${table('BRIDGE_LINES', bridge)}

${table('DECLARATION_LINES', declarations)}

/// The bridge script for one view: the injected source applied to its configuration.
///
/// The invoke key stays inside the script's closure; the page sees only the
/// functions the bridge exposes.
export fn script(key: Str, label: Str, dev: Bool) -> Str {
  let config = Json.object(&[("key", Json.Text(key)), ("label", Json.Text(label)), ("dev", Json.Boolean(dev))])
  BRIDGE_LINES.join("\\n") + "(" + Json.encode(&config) + ");"
}

/// The TypeScript declarations of the bridge every generated module imports.
export fn declarations() -> Str { DECLARATION_LINES.join("\\n") }
`;

if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8');
  if (current !== module) {
    console.error('Std/Desktop/Bridge.pudu is stale; run node scripts/desktop-bridge.mjs');
    process.exit(1);
  }
} else {
  writeFileSync(target, module);
}
